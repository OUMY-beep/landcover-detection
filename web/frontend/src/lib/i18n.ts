export type TranslationKey = keyof typeof translations.en;

export function translate(
  language: Language,
  key: TranslationKey,
  values: Record<string, string | number> = {},
): string {
  return translations[language][key].replace(/\{(\w+)\}/g, (_, name: string) => String(values[name] ?? `{${name}}`));
}

const classTranslationKeys: Record<string, TranslationKey> = {
  Ignore: 'classIgnore',
  Background: 'classBackground',
  Building: 'classBuilding',
  Road: 'classRoad',
  Water: 'classWater',
  Barren: 'classBarren',
  Forest: 'classForest',
  Agricultural: 'classAgricultural',
};

export function translateClassName(language: Language, className: string): string {
  const key = classTranslationKeys[className];
  return key ? translate(language, key) : className;
}
